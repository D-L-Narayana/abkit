def test_standard_labels_are_case_insensitive_and_mixed_spellings_warn() -> None:
    d = parse_csv_text("variant,converted\ncontrol,1\nTreatment,0\nCTRL,0\nTEST,1\nbaseline,1\n1,1\n0,0\nvariant,1\n")
    assert d.labels == {"control": "control", "treatment": "Treatment"}
    assert totals(d) == (4, 4, 2, 3)
    assert len(d.warnings) == 2
    assert "control, CTRL, baseline, 0" in d.warnings[0] and "Treatment, TEST, 1, variant" in d.warnings[1]
    plain = parse_csv_text("variant,converted\nA,1\nb,0\na,0\nB,1\n")
    assert plain.labels == {"control": "A", "treatment": "b"} and plain.warnings == ()


def test_unknown_label_pair_takes_the_first_seen_as_control_unless_named() -> None:
    text = "variant,converted\nnew,1\nold,0\nold,1\nnew,0\n"
    d = parse_csv_text(text)
    assert d.labels == {"control": "new", "treatment": "old"}
    assert any('"new"' in w and "control" in w for w in d.warnings)
    o = parse_csv_text(text, control_label="OLD")
    assert o.labels == {"control": "old", "treatment": "new"} and o.warnings == ()
    assert totals(o) == (2, 2, 1, 1)
    with pytest.raises(ValueError, match=r"zzz.*new.*old"):
        parse_csv_text(text, control_label="zzz")
    same = parse_csv_text("variant,converted\na,1\ncontrol,0\n")
    assert same.labels == {"control": "a", "treatment": "control"} and len(same.warnings) == 1


