def totals(d: ExperimentData) -> tuple[int, int, int, int]:
    return (d.n_a, d.n_b, d.conv_a, d.conv_b)


def assert_close(got: Any, want: Any, rel: float = 1e-12, path: str = "$") -> None:
    """Recursive comparison: exact for ints/strings/bools/None, relative tolerance for floats, same keys and lengths."""
    if isinstance(want, dict):
        assert isinstance(got, dict), path
        assert set(got) == set(want), f"{path}: keys {sorted(got)} != {sorted(want)}"
        for k in want:
            assert_close(got[k], want[k], rel, f"{path}.{k}")
    elif isinstance(want, list):
        assert isinstance(got, list) and len(got) == len(want), path
        for i, (g, w) in enumerate(zip(got, want, strict=True)):
            assert_close(g, w, rel, f"{path}[{i}]")
    elif isinstance(want, bool) or want is None or isinstance(want, str):
        assert got == want, f"{path}: {got!r} != {want!r}"
    elif isinstance(want, int) and not isinstance(got, float):
        assert got == want, f"{path}: {got!r} != {want!r}"
    else:
        assert isinstance(got, int | float), path
        assert got == pytest.approx(want, rel=rel, abs=1e-300), path


# --------------------------------------------------------------------------- RFC 4180 reader
def test_quoted_field_with_the_delimiter_stays_one_cell() -> None:
    d = parse_csv_text('variant,converted\nA,1\n"Variant, B",1\n"Variant, B",0\nA,0\n')
    assert d.fmt == "per-user" and d.metric_type == "conversion"
    assert d.labels == {"control": "A", "treatment": "Variant, B"}
    assert totals(d) == (2, 2, 1, 1)
    assert d.issues == () and d.rows == 4


def test_doubled_quotes_and_newlines_inside_quotes_and_physical_line_numbers() -> None:
    d = parse_csv_text('variant,converted\n"Ranker ""v2""",1\nA,0\n"Ranker ""v2""",0\n"A",1\n')
    assert d.treatment_label == 'Ranker "v2"'
    assert totals(d) == (2, 2, 1, 1)
    q = parse_csv_text('variant,converted\nA,1\n"Variant\nB",1\nA,oops\n"Variant\nB",0\n')
    assert q.treatment_label == "Variant\nB"
    assert [i.row for i in q.issues] == [5] and "converted" in q.issues[0].reason
    assert totals(q) == (1, 2, 1, 1)


def test_semicolon_crlf_bom_tab_and_decimal_comma() -> None:
    d = parse_csv_text("﻿variant;converted;day\r\nA;1;1\r\nB;0;1\r\nA;0;2\r\nB;1;2\r\n")
    assert d.issues == ()
    assert [x.day for x in d.days] == [1, 2]
    assert totals(d) == (2, 2, 1, 1)
    t = parse_csv_text("variant\tvalue\nA\t1.5\nB\t2.5\nA\t2.5\nB\t3.5\n")
    assert t.metric_type == "continuous" and not t.has_pre
    assert t.days[0].sums_a.sy == 4 and t.days[0].sums_b.sy == 6
    semi = parse_csv_text("variant;value\nA;12,5\nB;10,0\nA;7,5\nB;9\n")
    assert semi.days[0].sums_a.sy == 20 and semi.days[0].sums_b.sy == 19
    comma = parse_csv_text("variant,value\nA,1,5\nB,2\nA,1\nB,2\n")  # with a comma delimiter "1,5" is two cells → wrong width, skipped
    assert [i.row for i in comma.issues] == [2] and comma.rows == 3


def test_blank_lines_are_ignored_and_rows_with_the_wrong_width_are_skipped() -> None:
    d = parse_csv_text("variant,converted,day\nA,1,1\n\nB,1\nA,0,1\nB,0,1\n\n")
    assert d.issues == (Issue(4, "expected 3 columns, got 2"),)
    assert d.rows == 3 and totals(d) == (2, 1, 1, 0)


