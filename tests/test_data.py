def test_days_are_sorted_and_iso_dates_are_numbered_from_the_earliest() -> None:
    d = parse_csv_text("variant,converted,day\nA,1,3\nB,0,1\nA,0,2\nB,1,3\nA,1,1\nB,0,2\n")
