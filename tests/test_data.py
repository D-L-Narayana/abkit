def test_aggregated_conversion_layout() -> None:
    d = parse_csv_text("variant,users,conversions,day\nA,1000,100,1\nB,1000,120,1\nA,900,80,2\nB,950,99,2\n")
    assert d.fmt == "aggregated" and d.metric_type == "conversion" and d.rows == 4 and not d.has_pre
    empty = stats.Sums.empty()
    assert d.days == (DayAgg(1, 1000, 1000, 100, 120, empty, empty), DayAgg(2, 900, 950, 80, 99, empty, empty))
    s = parse_csv_text("variant,users,conversions\nA,1000,100\nA,500,40\nB,1500,160\nB,10,12\nA,-5,0\n")
    assert len(s.days) == 1 and (s.days[0].n_a, s.days[0].n_b, s.days[0].conv_a, s.days[0].conv_b) == (1500, 1500, 140, 160)
    assert [(i.row, i.reason.split(" ")[0]) for i in s.issues] == [(5, "conversions"), (6, "users")]


def test_aggregated_continuous_layout_reads_sums() -> None:
    d = parse_csv_text("variant,users,sum,sum_sq,pre_sum,pre_sum_sq,cross_sum,day\nA,3,30,320,27,251,275,1\nB,3,36,450,30,310,370,1\n")
    assert d.fmt == "aggregated" and d.has_pre and d.metric_type == "continuous"
    assert d.days[0].sums_a == stats.Sums(3, 27, 30, 251, 320, 275)
    assert d.days[0].sums_b == stats.Sums(3, 30, 36, 310, 450, 370)
    assert (d.days[0].n_a, d.days[0].n_b, d.days[0].conv_a, d.days[0].conv_b) == (3, 3, 0, 0)
    plain = parse_csv_text("variant,users,sum,sum_sq\nA,4,40,420\nB,4,44,500\nB,2,20,150\n")
    assert not plain.has_pre
    assert plain.days[0].sums_a == stats.Sums(4, 0, 40, 0, 420, 0)
    assert [i.row for i in plain.issues] == [4] and "sum_sq" in plain.issues[0].reason
    with pytest.raises(ValueError, match="pre_sum_sq"):
        parse_csv_text("variant,users,sum,sum_sq,pre_sum\nA,4,40,420,1\nB,4,44,500,2\n")


