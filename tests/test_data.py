def test_read_csv_accepts_paths_and_text_or_binary_file_objects(tmp_path: Path) -> None:
    text = "variant,converted,day\nA,1,1\nB,0,1\nA,0,2\nB,1,2\n"
    path = tmp_path / "x.csv"
    path.write_text("﻿" + text, encoding="utf-8")
    ref = parse_csv_text(text)
    assert ref.rows == 4
    assert read_csv(path) == ref
    assert read_csv(str(path)) == ref
    assert read_csv(StringIO(text)) == ref
    assert read_csv(BytesIO(("﻿" + text).encode("utf-8"))) == ref
    with path.open("rb") as fh:
        assert read_csv(fh) == ref
    with pytest.raises(ValueError):
        read_csv(path, control_label="C")


# --------------------------------------------------------------------------- analysis
def _conversion_text(conv_b: list[int]) -> str:
    rows = ["variant,users,conversions,day"]
    for day, (ca, cb) in enumerate(zip([100, 97, 104, 99], conv_b, strict=True), start=1):
        rows += [f"A,1000,{ca},{day}", f"B,1000,{cb},{day}"]
    return "\n".join(rows) + "\n"


def test_analyze_conversion_matches_the_component_statistics() -> None:
    r = analyze(parse_csv_text(_conversion_text([112, 118, 125, 121])))
    assert r["metric_type"] == "conversion" and r["format"] == "aggregated" and r["days"] == 4
    assert (r["n_a"], r["n_b"], r["conv_a"], r["conv_b"]) == (4000, 4000, 400, 476)
    z = stats.two_proportion_ztest(400, 4000, 476, 4000)
    assert r["test"]["kind"] == "two_proportion_z"
    assert r["test"]["statistic"] == z.z and r["test"]["p_value"] == z.p_value
    assert r["test"]["p_value"] == pytest.approx(2 * sps.norm.sf(abs(z.z)))
    assert (r["test"]["ci_low"], r["test"]["ci_high"]) == (z.ci_low, z.ci_high)
    assert r["relative_lift"] == stats.relative_lift_proportions(400, 4000, 476, 4000).as_dict()
    srm = stats.srm_check([4000, 4000], [0.5, 0.5])
    assert r["srm"] == {"chi2": srm.chi2, "p_value": srm.p_value, "mismatch": False, "expected": [4000.0, 4000.0]}
    seq = sequential.msprt_proportions([100, 197, 301, 400], [1000, 2000, 3000, 4000], [112, 230, 355, 476], [1000, 2000, 3000, 4000], tau=0.1 * 0.05)
    assert r["sequential"]["tau"] == 0.1 * 0.05
    assert r["sequential"]["always_valid_p"] == list(seq.always_valid_p)
    assert r["sequential"]["decided_day"] == seq.decided_at
    assert [p["day"] for p in r["series"]] == [1, 2, 3, 4]
    assert [p["n"] for p in r["series"]] == [2000, 4000, 6000, 8000]
    assert [p["always_valid_p"] for p in r["series"]] == list(seq.always_valid_p)
    last = r["series"][-1]
    assert last["p_value"] == z.p_value and last["lift_rel"] == r["relative_lift"]["lift_rel"]
    assert (last["ci_low"], last["ci_high"]) == (r["relative_lift"]["ci_low"], r["relative_lift"]["ci_high"])
    first = stats.two_proportion_ztest(100, 1000, 112, 1000)
    assert r["series"][0]["p_value"] == first.p_value
    assert r["cuped"] is None
    assert r["verdict"] == {"decision": "winner", "basis": "fixed", "reason": r["verdict"]["reason"]}
    assert r["progress"] == 1.0 and r["planned_per_arm"] is None
    assert r["labels"] == {"control": "A", "treatment": "B"} and r["rows"] == 8 and r["skipped"] == [] and r["warnings"] == []
    json.dumps(r, allow_nan=False)


def test_analyze_verdict_rules_and_options() -> None:
    small = parse_csv_text(_conversion_text([112, 118, 125, 121]))
    r = analyze(small, planned_per_arm=10_000)
    assert r["progress"] == pytest.approx(0.4) and r["planned_per_arm"] == 10_000
    assert r["verdict"]["decision"] == "collecting" and r["verdict"]["basis"] == "fixed"
    big = parse_csv_text(_conversion_text([150, 148, 155, 152]))
    r = analyze(big, planned_per_arm=10_000)
    assert r["sequential"]["always_valid_p"][-1] < 0.05 and r["sequential"]["decided_day"] is not None
    assert r["verdict"]["decision"] == "winner" and r["verdict"]["basis"] == "sequential"
    assert str(r["sequential"]["decided_day"]) in r["verdict"]["reason"]
    loser = parse_csv_text(_conversion_text([60, 58, 55, 62]))
    assert analyze(loser)["verdict"] | {"reason": ""} == {"decision": "loser", "basis": "fixed", "reason": ""}
    flat = parse_csv_text(_conversion_text([101, 96, 105, 98]))
    assert analyze(flat)["verdict"]["decision"] == "flat"
    skew = parse_csv_text("variant,users,conversions\nA,4000,400\nB,4800,480\n")
    r = analyze(skew)
    assert r["srm"]["mismatch"] is True and r["srm"]["p_value"] < 1e-6
    assert r["verdict"] | {"reason": ""} == {"decision": "invalid", "basis": "fixed", "reason": ""}
    assert analyze(skew, split=4000 / 8800)["srm"]["mismatch"] is False
    strict = analyze(small, alpha=0.01)
    assert strict["test"]["ci_low"] < analyze(small)["test"]["ci_low"] and strict["alpha"] == 0.01  # wider interval at a stricter alpha
    assert analyze(small, mde_rel=0.1)["sequential"]["tau"] == pytest.approx(0.1 * 0.1)
    with pytest.raises(ValueError):
        analyze(small, alpha=0.0)
    with pytest.raises(ValueError):
        analyze(small, alpha=1.0)
    with pytest.raises(ValueError):
        analyze(small, split=1.0)
    with pytest.raises(ValueError):
        analyze(small, mde_rel=0.0)
    with pytest.raises(ValueError):
        analyze(small, planned_per_arm=-1)


def _continuous_text(with_pre: bool, seed: int = 1) -> tuple[str, dict[str, tuple[np.ndarray, np.ndarray]]]:
    rng = np.random.default_rng(seed)
    rows = ["variant,value,pre_value,day" if with_pre else "variant,value,day"]
    arms: dict[str, tuple[np.ndarray, np.ndarray]] = {}
    for label, mean in (("control", 100.0), ("treatment", 103.0)):
        z1, z2 = rng.standard_normal(800), rng.standard_normal(800)
        pre = np.round(100 + 30 * z1, 4)
        val = np.round(mean + 40 * (0.6 * z1 + 0.8 * z2), 4)
        arms[label] = (pre, val)
        for i in range(800):
            day = 1 if i < 400 else 2
            rows.append(f"{label},{float(val[i]):.4f},{float(pre[i]):.4f},{day}" if with_pre else f"{label},{float(val[i]):.4f},{day}")
    return "\n".join(rows) + "\n", arms


def test_analyze_continuous_with_and_without_cuped() -> None:
    text, arms = _continuous_text(True)
    data = parse_csv_text(text)
    assert data.metric_type == "continuous" and data.has_pre and len(data.days) == 2 and data.rows == 1600
    r = analyze(data)
    last = data.cumulative()[-1]
    a, b = last.sums_a.mean_var(), last.sums_b.mean_var()
    raw = stats.welch_ttest_from_stats(a, b)
    assert r["test"]["kind"] == "welch_t"
    assert (r["test"]["statistic"], r["test"]["df"], r["test"]["p_value"]) == (raw.t, raw.df, raw.p_value)
    assert (r["test"]["mean_a"], r["test"]["mean_b"], r["test"]["ci_low"], r["test"]["ci_high"]) == (raw.mean_a, raw.mean_b, raw.ci_low, raw.ci_high)
    ref = sps.ttest_ind(arms["treatment"][1], arms["control"][1], equal_var=False)
    assert r["test"]["p_value"] == pytest.approx(ref.pvalue, rel=1e-9)
    c = stats.cuped_from_sums(last.sums_a, last.sums_b)
    adj = stats.welch_ttest_from_stats(c.adj_a, c.adj_b)
    cu = r["cuped"]
    assert cu is not None and cu["theta"] == c.theta and cu["variance_reduction"] == c.variance_reduction
    assert cu["variance_reduction"] > 0.2
    assert cu["adjusted_test"]["p_value"] == adj.p_value and cu["adjusted_test"]["kind"] == "welch_t"
    assert r["relative_lift"] == stats.relative_lift_means(c.adj_a, c.adj_b).as_dict()
    assert r["relative_lift_raw"] == stats.relative_lift_means(a, b).as_dict()
    assert r["sequential"]["tau"] == abs(a.mean * 0.05)
    looks_a, looks_b = [], []
    for d in data.cumulative():
        ck = stats.cuped_from_sums(d.sums_a, d.sums_b)
        looks_a.append(ck.adj_a)
        looks_b.append(ck.adj_b)
    seq = sequential.msprt_means(looks_a, looks_b, tau=abs(a.mean * 0.05))
    assert r["sequential"]["always_valid_p"] == list(seq.always_valid_p)
    assert r["sequential"]["decided_day"] == (data.days[seq.decided_at - 1].day if seq.decided_at else None)
    s = r["series"][-1]
    assert s["p_value"] == adj.p_value and s["p_value_raw"] == raw.p_value
    assert (s["lift_rel"], s["ci_low"], s["ci_high"]) == (r["relative_lift"]["lift_rel"], r["relative_lift"]["ci_low"], r["relative_lift"]["ci_high"])
    assert (s["ci_low_raw"], s["ci_high_raw"]) == (r["relative_lift_raw"]["ci_low"], r["relative_lift_raw"]["ci_high"])
    assert (r["conv_a"], r["conv_b"]) == (0, 0) and r["has_pre"] is True
    json.dumps(r, allow_nan=False)

    plain, _ = _continuous_text(False)
    r2 = analyze(parse_csv_text(plain))
    assert r2["cuped"] is None and r2["has_pre"] is False
    assert r2["test"]["p_value"] == raw.p_value
    assert r2["relative_lift"] == stats.relative_lift_means(a, b).as_dict()
    assert r2["series"][-1]["p_value"] == raw.p_value


