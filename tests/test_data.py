def test_expected_json_matches_analyze_for_every_fixture() -> None:
    path = FIXTURES / "expected.json"
    assert path.is_file(), f"missing expected.json — {REGENERATE}"
    expected = json.loads(path.read_text(encoding="utf-8"))
    assert set(expected) == set(FIXTURE_FILES)
    for name in FIXTURE_FILES:
        if name == ERROR_FIXTURE:
            with pytest.raises(ValueError) as exc:
                read_csv(FIXTURES / name)
            assert expected[name] == {"error": str(exc.value)}
            continue
        got = analyze(read_csv(FIXTURES / name))
        assert_close(got, expected[name])
        assert {"metric_type", "format", "days", "n_a", "n_b", "conv_a", "conv_b", "srm", "test", "relative_lift", "cuped", "sequential", "series", "verdict"} <= set(got)


def test_make_fixtures_regenerates_identical_files(tmp_path: Path) -> None:
    spec = importlib.util.spec_from_file_location("make_fixtures", FIXTURES / "make_fixtures.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.build(tmp_path)
    for name in FIXTURE_FILES:
        assert (tmp_path / name).read_bytes() == (FIXTURES / name).read_bytes(), f"{name} differs — {REGENERATE}"
    regenerated = json.loads((tmp_path / "expected.json").read_text(encoding="utf-8"))
    committed = json.loads((FIXTURES / "expected.json").read_text(encoding="utf-8"))
    assert_close(regenerated, committed)
